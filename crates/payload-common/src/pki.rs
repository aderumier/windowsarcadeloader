/// Whether the SHA-1 dummy PKI is used (`WAL_BILLING_SHA1=1`).
pub fn sha1() -> bool {
    std::env::var("WAL_BILLING_SHA1").is_ok_and(|v| v.trim() == "1")
}

/// The CA certificate the keychip gives the game.
pub fn ca_cert() -> &'static [u8] {
    if sha1() { CA_CERT_SHA1 } else { CA_CERT }
}
